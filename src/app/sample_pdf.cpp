std::string make_sample_pdf() {
    // Object numbering:
    // 1 catalog, 2 pages, 3 outlines, 4 info, 5 F1, 6 F2,
    // then per page: page object, content stream, outline item, (page 1: two link annots).
    std::vector<std::string> objects;  // index 0 == object 1
    const auto reserve = [&]() { objects.emplace_back(); return static_cast<int>(objects.size()); };
    const auto set = [&](int number, const std::string& body) { objects[static_cast<size_t>(number - 1)] = body; };

    const int catalog = reserve(), pages = reserve(), outlines = reserve(), info = reserve(), f1 = reserve(), f2 = reserve();
    std::vector<int> page_ids, content_ids, outline_ids;
    for (int i = 0; i < kSamplePageCount; ++i) { page_ids.push_back(reserve()); content_ids.push_back(reserve()); outline_ids.push_back(reserve()); }
    const int link_goto = reserve(), link_uri = reserve();

    char buffer[1024];
    std::string kids;
    for (int id : page_ids) { std::snprintf(buffer, sizeof buffer, "%d 0 R ", id); kids += buffer; }

    set(catalog, "<< /Type /Catalog /Pages 2 0 R /Outlines 3 0 R /PageMode /UseOutlines >>");
    std::snprintf(buffer, sizeof buffer, "<< /Type /Pages /Kids [ %s] /Count %d >>", kids.c_str(), kSamplePageCount);
    set(pages, buffer);
    std::snprintf(buffer, sizeof buffer, "<< /Type /Outlines /First %d 0 R /Last %d 0 R /Count %d >>", outline_ids.front(), outline_ids.back(), kSamplePageCount);
    set(outlines, buffer);
    std::snprintf(buffer, sizeof buffer, "<< /Title (%s) /Author (davepdf) /Subject (Generated sample for the davepdf viewer) /Keywords (sample davepdf pdfium) /Creator (davepdf sample generator) /Producer (davepdf) /CreationDate (D:20261024090000Z) >>", kSampleTitle);
    set(info, buffer);
    set(f1, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>");
    set(f2, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>");

    for (int i = 0; i < kSamplePageCount; ++i) {
        const bool landscape = i == 1;
        const std::string content = page_content(i + 1, landscape);
        std::string annots;
        if (i == 0) { std::snprintf(buffer, sizeof buffer, " /Annots [ %d 0 R %d 0 R ]", link_goto, link_uri); annots = buffer; }
        std::snprintf(buffer, sizeof buffer,
                      "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] /Contents %d 0 R /Resources << /Font << /F1 %d 0 R /F2 %d 0 R >> >>%s >>",
                      landscape ? 842 : 612, landscape ? 595 : 792, content_ids[static_cast<size_t>(i)], f1, f2, annots.c_str());
        set(page_ids[static_cast<size_t>(i)], buffer);
        std::snprintf(buffer, sizeof buffer, "<< /Length %zu >>\nstream\n", content.size());
        set(content_ids[static_cast<size_t>(i)], std::string(buffer) + content + "\nendstream");
        std::string links;
        if (i > 0) { std::snprintf(buffer, sizeof buffer, " /Prev %d 0 R", outline_ids[static_cast<size_t>(i - 1)]); links += buffer; }
        if (i + 1 < kSamplePageCount) { std::snprintf(buffer, sizeof buffer, " /Next %d 0 R", outline_ids[static_cast<size_t>(i + 1)]); links += buffer; }
        const char* titles[] = {"Welcome", "A landscape page", "The last page"};
        std::snprintf(buffer, sizeof buffer, "<< /Title (%s) /Parent 3 0 R%s /Dest [ %d 0 R /Fit ] >>", titles[i], links.c_str(), page_ids[static_cast<size_t>(i)]);
        set(outline_ids[static_cast<size_t>(i)], buffer);
    }
    std::snprintf(buffer, sizeof buffer, "<< /Type /Annot /Subtype /Link /Rect [ 36 552 160 574 ] /Border [ 0 0 0 ] /Dest [ %d 0 R /Fit ] >>", page_ids.back());
    set(link_goto, buffer);
    set(link_uri, "<< /Type /Annot /Subtype /Link /Rect [ 36 528 140 550 ] /Border [ 0 0 0 ] /A << /S /URI /URI (https://example.com/) >> >>");

    std::string out = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
    std::vector<size_t> offsets;
    for (size_t i = 0; i < objects.size(); ++i) {
        offsets.push_back(out.size());
        std::snprintf(buffer, sizeof buffer, "%zu 0 obj\n", i + 1);
        out += buffer;
        out += objects[i];
        out += "\nendobj\n";
    }
    const size_t xref = out.size();
    std::snprintf(buffer, sizeof buffer, "xref\n0 %zu\n0000000000 65535 f \n", objects.size() + 1);
    out += buffer;
    for (size_t offset : offsets) { std::snprintf(buffer, sizeof buffer, "%010zu 00000 n \n", offset); out += buffer; }
    std::snprintf(buffer, sizeof buffer, "trailer\n<< /Size %zu /Root 1 0 R /Info 4 0 R >>\nstartxref\n%zu\n%%%%EOF\n", objects.size() + 1, xref);
    out += buffer;
    return out;
}

