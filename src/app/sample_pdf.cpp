void appendf(std::string& out, const char* format, ...) {
    char buffer[4096];
    va_list args;
    va_start(args, format);
    std::vsnprintf(buffer, sizeof buffer, format, args);
    va_end(args);
    out += buffer;
}

std::string page_content(int page, bool landscape) {
    // Page 1 is a cover with a coloured header band, body copy and two link
    // targets; later pages vary the layout so scrolling has something to show.
    const float width = landscape ? 842.0f : 612.0f, height = landscape ? 595.0f : 792.0f;
    std::string s;
    const auto add = [&](const char* text) { s += text; };
    const auto addf = [&](const char* format, auto... args) { appendf(s, format, args...); };

    // Header band.
    addf("0.784 0.188 0.188 rg 0 %.0f %.0f 72 re f\n", static_cast<double>(height - 72), static_cast<double>(width));
    add("BT 1 1 1 rg /F2 22 Tf 36 ");
    addf("%.0f Td (%s) Tj ET\n", static_cast<double>(height - 46), kSampleTitle);
    addf("BT 0.2 0.2 0.22 rg /F1 12 Tf 36 %.0f Td (sample page %d of %d) Tj ET\n", static_cast<double>(height - 100), page, kSamplePageCount);

    if (page == 1) {
        add("BT 0.1 0.1 0.12 rg /F2 16 Tf 36 650 Td (Welcome) Tj ET\n");
        add("BT 0.15 0.15 0.18 rg /F1 11 Tf 36 628 Td 15 TL\n");
        add("(This document is generated by davepdf itself, so it is available without a) Tj T*\n");
        add("(file at hand. It has three pages of different sizes, an outline, a text) Tj T*\n");
        add("(layer for searching, and two link annotations below.) Tj T*\n");
        add("ET\n");
        // Link targets drawn as underlined blue text; the annotations in the
        // page dictionary sit on top of these rectangles.
        add("BT 0.14 0.39 0.85 rg /F1 12 Tf 36 560 Td (Jump to the last page) Tj ET\n");
        add("0.14 0.39 0.85 RG 0.8 w 36 557 m 160 557 l S\n");
        add("BT 0.14 0.39 0.85 rg /F1 12 Tf 36 536 Td (Open example.com) Tj ET\n");
        add("36 533 m 140 533 l S\n");
        // A little geometry so rendering is visibly more than text.
        add("0.93 0.95 0.98 rg 36 300 540 200 re f\n");
        add("0.784 0.188 0.188 rg 60 330 80 140 re f\n");
        add("0.26 0.62 0.36 rg 160 330 80 90 re f\n");
        add("0.89 0.68 0.35 rg 260 330 80 160 re f\n");
        add("0.35 0.55 0.93 rg 360 330 80 60 re f\n");
        add("0.45 0.45 0.5 RG 1 w 50 330 m 560 330 l S\n");
        add("BT 0.3 0.3 0.34 rg /F1 9 Tf 48 310 Td (Vector graphics render through PDFium at any zoom level.) Tj ET\n");
    } else if (page == 2) {
        add("BT 0.1 0.1 0.12 rg /F2 16 Tf 36 470 Td (A landscape page) Tj ET\n");
        add("BT 0.15 0.15 0.18 rg /F1 11 Tf 36 448 Td 15 TL\n");
        add("(Pages do not have to share a size. The viewer centres each page in the) Tj T*\n");
        add("(column and fit-to-width follows the widest page in the document.) Tj T*\n");
        add("ET\n");
        for (int row = 0; row < 6; ++row) {
            addf("%s %.0f %.0f %.0f 24 re f\n", row % 2 ? "0.93 0.93 0.95 rg" : "0.98 0.98 0.99 rg", 36.0, 380.0 - row * 24, static_cast<double>(width - 72));
            addf("BT 0.2 0.2 0.22 rg /F1 10 Tf 44 %.0f Td (Row %d) Tj 200 0 Td (Column two) Tj 200 0 Td (Column three) Tj ET\n", 388.0 - row * 24, row + 1);
        }
    } else {
        add("BT 0.1 0.1 0.12 rg /F2 16 Tf 36 650 Td (The last page) Tj ET\n");
        add("BT 0.15 0.15 0.18 rg /F1 11 Tf 36 628 Td 15 TL\n");
        add("(Searching for a word highlights every hit and steps through them in) Tj T*\n");
        add("(reading order. Try searching for the word landscape.) Tj T*\n");
        add("ET\n");
        add("0.784 0.188 0.188 RG 3 w 306 420 m 406 520 l 206 520 l h S\n");
        add("0.35 0.55 0.93 RG 2 w 256 300 m 356 300 l 356 400 l 256 400 l h S\n");
    }
    return s;
}

